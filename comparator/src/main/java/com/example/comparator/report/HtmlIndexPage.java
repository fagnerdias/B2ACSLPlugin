/** {@code index.html}: run settings, outcome tiles (which double as filters) and one row per example. */
final class HtmlIndexPage {

    private static final int NOTE_CHARS = 160;

    private HtmlIndexPage() {}

    static String render(Summary summary, Map<String, ExampleReport> reports) {
        RunConfig config = summary.config();
        StringBuilder b = new StringBuilder();
        b.append("<header class=\"top\"><h1>B2ACSLPlugin × B2ACSLRules</h1><span class=\"muted\">")
                .append(esc(HtmlRunInfo.when(summary.generatedAt()))).append("</span></header>\n")
                .append("<p class=\"sub\">Specifications generated by the two B → ACSL translators from the same B projects, ")
                .append("and the Frama-C/WP results of each one.</p>\n")
                .append(HtmlRunInfo.configCard(config));

        // without verification there are no outcomes to count or WP columns to show
        boolean verify = config == null || config.verify();
        b.append("<section data-filter-root>\n");
        if (verify) {
            b.append(tiles(summary.examples())).append(proofHeadline(summary.examples()));
        }
        boolean meaning = summary.examples().stream().anyMatch(r -> r.spec() != null && r.spec().hasMeaning());
        if (meaning) {
            b.append(specHeadline(summary.examples(), reports));
        }
        b.append("<h2>Examples</h2>\n")
                .append("<div class=\"controls\"><input type=\"search\" data-search placeholder=\"Filter examples\" ")
                .append("aria-label=\"Filter examples by name\"><span class=\"shown\" data-shown></span></div>\n")
                .append(Html.unitsLegend(meaning))
                .append(table(summary.examples(), reports, config, verify));
        b.append("</section>\n");
        return Html.page("B2ACSL comparison", b.toString());
    }

    /** Count per outcome; clicking a tile filters the table (clicking it again clears the filter). */
    private static String tiles(List<SummaryRow> rows) {
        Map<Outcome, Integer> counts = new EnumMap<>(Outcome.class);
        rows.forEach(row -> counts.merge(Outcome.of(row), 1, Integer::sum));
        StringBuilder b = new StringBuilder("<div class=\"tiles\" data-group=\"outcome\" data-clearable>\n");
        b.append(tile("*", "", "Examples", rows.size(), "show all", true));
        for (Outcome o : Outcome.values()) {
            b.append(tile(o.id, o.swatches(), o.label, counts.getOrDefault(o, 0), hint(o), false));
        }
        return b.append("</div>\n").toString();
    }

    private static String hint(Outcome o) {
        return switch (o) {
            case BOTH -> "both sides finished WP";
            case PLUGIN -> "rules side failed";
            case RULES -> "plugin side failed";
            case PARTIAL -> "WP stopped early";
            case NEITHER -> "no WP result";
        };
    }

    private static String tile(String value, String swatches, String label, int count, String hint, boolean pressed) {
        return "<button type=\"button\" class=\"tile\" data-value=\"" + value + "\" aria-pressed=\"" + pressed + "\">"
                + "<div class=\"label\">" + swatches + esc(label) + "</div><div class=\"value\">" + num(count)
                + "</div><div class=\"hint\">" + esc(hint) + "</div></button>\n";
    }

    /**
     * Units by kind of difference, summed over the examples both translators generated (an example
     * one side could not translate would count every unit of the other side as a difference), and
     * the rewrites that explain the units with the same meaning.
     */
    private static String specHeadline(List<SummaryRow> rows, Map<String, ExampleReport> reports) {
        int examples = 0;
        int[] t = new int[6]; // units, identical, same meaning, different, only plugin, only rules
        Map<String, Integer> rules = new java.util.TreeMap<>();
        for (SummaryRow r : rows) {
            SpecSummary s = r.spec();
            if (s == null || !s.hasMeaning() || !"OK".equals(r.pluginGeneration()) || !"OK".equals(r.rulesGeneration())) {
                continue;
            }
            examples++;
            t[0] += s.units();
            t[1] += s.equalUnits();
            t[2] += s.sameMeaningUnits();
            t[3] += s.meaningBothUnits();
            t[4] += s.meaningOnlyPluginUnits();
            t[5] += s.meaningOnlyRulesUnits();
            ExampleReport report = reports.get(r.example());
            if (report != null && report.spec() != null && report.spec().formRules() != null) {
                report.spec().formRules().forEach((rule, n) -> rules.merge(rule, n, Integer::sum));
            }
        }
        if (examples == 0) {
            return "";
        }
        SpecSummary total = new SpecSummary(t[0], t[1], 0, 0, 0, 0, 0, 0, t[2], t[3], t[4], t[5], 0, 0, 0);
        StringBuilder b = new StringBuilder("<h2>Specification differences on the ").append(examples)
                .append(" examples both translators generated</h2>\n<div class=\"card\">")
                .append(Html.unitsBar(total, true)).append(Html.unitsLegend(true))
                .append("<div class=\"muted small\">").append(num(t[0])).append(" units: ")
                .append(num(t[1])).append(" identical, ").append(num(t[2])).append(" with the same meaning written differently, ")
                .append(num(t[3] + t[4] + t[5])).append(" with a different meaning (").append(num(t[3])).append(" on both sides, ")
                .append(num(t[4])).append(" only in plugin, ").append(num(t[5])).append(" only in rules).</div>");
        if (!rules.isEmpty()) {
            b.append("<details class=\"block\"><summary>Rewrites that explain the units with the same meaning</summary>")
                    .append("<div class=\"tablewrap\"><table class=\"rules-table\"><tbody>");
            rules.entrySet().stream()
                    .sorted(Map.Entry.<String, Integer>comparingByValue().reversed().thenComparing(Map.Entry.comparingByKey()))
                    .forEach(e -> {
                        com.example.comparator.spec.meaning.MeaningRule rule =
                                com.example.comparator.spec.meaning.MeaningRule.byId(e.getKey());
                        b.append("<tr><td>").append(esc(rule == null ? e.getKey() : rule.label()))
                                .append("</td><td class=\"n\">").append(num(e.getValue())).append("</td><td class=\"d\">")
                                .append(esc(rule == null ? "" : rule.description())).append("</td></tr>");
                    });
            b.append("</tbody></table></div></details>");
        }
        return b.append("</div>\n").toString();
    }

    /** Goals proved by each side, summed over the examples both sides verified. */
    private static String proofHeadline(List<SummaryRow> rows) {
        List<SummaryRow> both = rows.stream().filter(r -> Outcome.of(r) == Outcome.BOTH).toList();
        if (both.isEmpty()) {
            return "";
        }
        long pp = 0;
        long pt = 0;
        long rp = 0;
        long rt = 0;
        int pluginHigher = 0;
        int rulesHigher = 0;
        int same = 0;
        for (SummaryRow r : both) {
            pp += r.pluginProved();
            pt += r.pluginTotal();
            rp += r.rulesProved();
            rt += r.rulesTotal();
            int cmp = Double.compare(ratio(r.pluginProved(), r.pluginTotal()), ratio(r.rulesProved(), r.rulesTotal()));
            if (cmp > 0) {
                pluginHigher++;
            } else if (cmp < 0) {
                rulesHigher++;
            } else {
                same++;
            }
        }
        return "<h2>Proof results on the " + both.size() + " examples both sides verified</h2>\n<div class=\"duel\">"
                + duelCard("plugin", pp, pt, pluginHigher)
                + duelCard("rules", rp, rt, rulesHigher)
                + "</div>\n<p class=\"muted small\">" + same + " example" + (same == 1 ? "" : "s")
                + " with the same proved share on both sides. Totals differ because the two specifications differ, "
                + "so compare shares, and open an example for its per-function results.</p>\n";
    }

    private static String duelCard(String side, long proved, long total, int higher) {
        double ratio = ratio(proved, total);
        String tip = Html.label(side) + ": " + num(proved) + " of " + num(total) + " goals proved (" + Html.pct(ratio) + ")";
        return "<div class=\"card\"><h3>" + Html.swatch(side) + " " + Html.label(side) + "</h3>"
                + "<div class=\"big\">" + Html.pct(ratio) + "</div>" + Html.meter(side, ratio, tip)
                + "<div class=\"muted small\">" + num(proved) + " of " + num(total) + " goals proved · higher share on "
                + higher + " example" + (higher == 1 ? "" : "s") + "</div></div>";
    }

    /** With {@code verify} off, the outcome column goes away and the side columns show the generation status. */
    private static String table(List<SummaryRow> rows, Map<String, ExampleReport> reports, RunConfig config, boolean verify) {
        String sideColumn = verify ? " WP</th>" : " generation</th>";
        StringBuilder b = new StringBuilder("<div class=\"tablewrap\"><table class=\"sortable\">\n<thead><tr>")
                .append("<th data-sort=\"text\" aria-sort=\"ascending\">Example</th>")
                .append(verify ? "<th data-sort=\"num\">Outcome</th>" : "")
                .append("<th data-sort=\"num\">Specification units</th>")
                .append("<th data-sort=\"num\">").append(Html.swatch("plugin")).append(" Plugin").append(sideColumn)
                .append("<th data-sort=\"num\">").append(Html.swatch("rules")).append(" Rules").append(sideColumn)
                .append("<th>Notes</th></tr></thead>\n<tbody>\n");
        int functionTimeout = config == null ? 0 : config.functionTimeout();
        for (SummaryRow row : rows) {
            b.append(row(row, reports.get(row.example()), functionTimeout, verify));
        }
        return b.append("</tbody></table></div>\n").toString();
    }

    private static String row(SummaryRow row, ExampleReport report, int functionTimeout, boolean verify) {
        Outcome outcome = Outcome.of(row);
        SpecSummary spec = row.spec();
        String name = esc(row.example());
        String link = report == null ? name
                : "<a href=\"" + esc(row.example()) + "/" + HtmlReport.EXAMPLE_FILE + "\">" + name + "</a>";
        String sides = verify
                ? wpCell("plugin", row.pluginGeneration(), row.pluginVerification(), row.pluginProved(), row.pluginTotal())
                        + wpCell("rules", row.rulesGeneration(), row.rulesVerification(), row.rulesProved(), row.rulesTotal())
                : generationCell(row.pluginGeneration()) + generationCell(row.rulesGeneration());
        return "<tr data-item data-outcome=\"" + outcome.id + "\" data-text=\"" + esc(row.example().toLowerCase(Locale.ROOT)) + "\">"
                + "<td class=\"name\" data-v=\"" + esc(row.example().toLowerCase(Locale.ROOT)) + "\">" + link + "</td>"
                + (verify ? "<td data-v=\"" + outcome.ordinal() + "\"><span class=\"outcome\">" + outcome.swatches()
                        + esc(outcome.shortLabel) + "</span></td>" : "")
                + "<td data-v=\"" + unitRatio(spec) + "\"><span class=\"wp\">" + Html.unitsBar(spec, false)
                + "<span class=\"counts tabnum\">" + unitCounts(spec)
                + "</span></span></td>"
                + sides
                + "<td class=\"note\">" + notes(report, functionTimeout) + "</td></tr>\n";
    }

    private static String generationCell(String status) {
        return "<td data-v=\"" + Html.Tone.of(status).ordinal() + "\">" + Html.chip(status) + "</td>";
    }

    /** WP numbers, under the failing status when the side did not complete (a generation failure first). */
    private static String wpCell(String side, String generation, String verification, int proved, int total) {
        String status = "OK".equals(generation) ? verification : generation;
        boolean completed = "COMPLETED".equals(status);
        String chip = completed ? "" : "<div class=\"cell-status\">" + Html.chip(status) + "</div>";
        double sortKey = total > 0 ? ratio(proved, total) : -1;
        String numbers = total > 0 || completed ? Html.wp(side, proved, total) : "";
        return "<td data-v=\"" + sortKey + "\">" + chip + numbers + "</td>";
    }

    private static String notes(ExampleReport report, int functionTimeout) {
        if (report == null) {
            return "<span class=\"muted\">report.json missing</span>";
        }
        StringBuilder b = new StringBuilder();
        for (String side : List.of("plugin", "rules")) {
            GenerationReport g = report.generation() == null ? null : report.generation().get(side);
            VerificationReport v = report.verification() == null ? null
                    : "plugin".equals(side) ? report.verification().plugin() : report.verification().rules();
            String reason = HtmlReport.failureReason(g, v, functionTimeout);
            if (reason != null) {
                b.append("<div class=\"note-line\" data-tip=\"").append(esc(Html.label(side) + ": " + reason)).append("\">")
                        .append(Html.swatch(side)).append("<span class=\"t\">").append(esc(Html.cut(reason, NOTE_CHARS)))
                        .append("</span></div>");
            }
        }
        return b.toString();
    }

    private static String unitCounts(SpecSummary spec) {
        if (spec == null) {
            return "";
        }
        if (spec.hasMeaning()) {
            return num(spec.equalUnits() + spec.sameMeaningUnits()) + "/" + num(spec.units()) + " same meaning";
        }
        return num(spec.equalUnits()) + "/" + num(spec.units()) + " equal";
    }

    /** Share of units with the same meaning (identical or written differently). */
    private static double unitRatio(SpecSummary spec) {
        if (spec == null || spec.units() == 0) {
            return -1;
        }
        int same = spec.equalUnits() + (spec.hasMeaning() ? spec.sameMeaningUnits() : 0);
        return ratio(same, spec.units());
    }

    private static double ratio(long part, long whole) {
        return whole <= 0 ? 0 : (double) part / whole;
    }
}
