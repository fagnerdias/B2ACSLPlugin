package com.example.comparator;

import com.example.comparator.util.FileTrees;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.stream.Stream;

/**
 * Isolated directories of one example: {@code <root>/plugin/{bdp,lang/c}} and {@code
 * <root>/rules/{bdp,lang/c}}. Both tools write files with the same names ({@code
 * connection.acsl}, {@code ghost_operations.ci}, {@code merged_code.c}, ...), so each one gets its
 * own copy of the inputs.
 */
public record Workspace(Path root) {

    public static final String REPORT_FILE = "report.json";
    public static final String SIDE_RESULT_FILE = "side-result.json";

    public Path sideRoot(Side side) {
        return root.resolve(side.id());
    }

    /**
     * The plugin derives its output folder from the bdp path ({@code .../bdp} becomes {@code
     * .../lang/c}), so both sides keep the Atelier B layout.
     */
    public Path bdp(Side side) {
        return sideRoot(side).resolve("bdp");
    }

    public Path cDir(Side side) {
        return sideRoot(side).resolve("lang").resolve("c");
    }

    /** Copy of the generated specification taken before verification (which may rename symbols in place). */
    public Path specSnapshot(Side side) {
        return sideRoot(side).resolve("spec");
    }

    public Path sideResult(Side side) {
        return sideRoot(side).resolve(SIDE_RESULT_FILE);
    }

    public Path sideLog(Side side) {
        return sideRoot(side).resolve("run.log");
    }

    public Path report() {
        return root.resolve(REPORT_FILE);
    }

    /**
     * Creates the workspace for {@code exampleDir} under {@code root}, copying only the inputs:
     * {@code bdp/**}{@code /*.bxml} and the Atelier B C code {@code lang/c/*.c,*.h} (never files
     * generated by an earlier run, such as {@code .acsl} or {@code merged_code.c}).
     */
    public static Workspace prepare(Path exampleDir, Path root) throws IOException {
        if (Files.isDirectory(root)) {
            try (Stream<Path> entries = Files.list(root)) {
                if (entries.findAny().isPresent()) {
                    throw new IOException("workspace already exists and is not empty: " + root);
                }
            }
        }
        Workspace ws = new Workspace(root.toAbsolutePath().normalize());
        Path sourceBdp = exampleDir.resolve("bdp");
        Path sourceC = exampleDir.resolve("lang").resolve("c");
        for (Side side : Side.values()) {
            Files.createDirectories(ws.bdp(side));
            Files.createDirectories(ws.cDir(side));
            FileTrees.copyTree(sourceBdp, ws.bdp(side), FileTrees.hasExtension(".bxml"));
            for (Path c : FileTrees.listFiles(sourceC, FileTrees.hasExtension(".c", ".h"))) {
                if (!c.getFileName().toString().equals("merged_code.c")) {
                    Files.copy(c, ws.cDir(side).resolve(c.getFileName().toString()));
                }
            }
        }
        return ws;
    }
}
