package com.example.comparator;

import java.nio.file.Path;
import java.time.LocalDateTime;
import java.time.format.DateTimeFormatter;
import java.util.ArrayList;
import java.util.List;

/**
 * Command-line options. The same object configures the parent (orchestrator) and, through {@link
 * #childArgs}, the child process that runs one side of one example.
 */
public record ComparatorConfig(
        List<String> examples,
        boolean all,
        Path examplesDir,
        Path outDir,
        Path rulesJar,
        Path libDir,
        String prover,
        int timeoutSeconds,
        int functionTimeoutSeconds,
        boolean perOperation,
        boolean verify,
        int rulesTimeoutSeconds,
        Side side,
        Path workspace) {

    static final String USAGE =
            """
            Usage: java -jar b2acsl-comparator-0.1.0-all.jar (--example NAME ... | --all) [options]

            Compares the specifications generated by B2ACSLPlugin and B2ACSLRules for the same
            B project, and the Frama-C/WP results of each one. Writes <out>/<example>/report.json
            and <out>/summary.json.

              --example NAME         example under --examples-dir (repeatable)
              --all                  every directory of --examples-dir that has a bdp/ folder
              --examples-dir DIR     default: examples
              --out DIR              default: comparator-out/<yyyyMMdd_HHmmss>
              --rules-jar FILE       B2ACSLRules translator; default: rules/dist/b2acsl.jar
              --lib-dir DIR          B2ACSLLib copied to import/ for the rules side;
                                     default: translate/src/main/resources/lib/B2ACSLLib
              --prover NAME[,NAME]   WP prover(s); default: CVC5
              --timeout N            WP timeout per goal (s); default: 10
              --function-timeout N   WP wall-clock limit per function (s); default: 600
              --whole-file           one WP run for the whole file instead of one per operation
              --no-verify            only compare the specifications (skip Frama-C)
              --rules-timeout N      limit for the B2ACSLRules translation (s); default: 300
              --help

            Other WP switches (smoke tests, counterexamples, goal splitting) follow the
            -Db2acsl.wp.* properties of the plugin, which are forwarded to both sides.
            """;

    static ComparatorConfig parse(String[] args) {
        List<String> examples = new ArrayList<>();
        boolean all = false;
        Path examplesDir = Path.of("examples");
        Path outDir = null;
        Path rulesJar = Path.of("rules", "dist", "b2acsl.jar");
        Path libDir = Path.of("translate", "src", "main", "resources", "lib", "B2ACSLLib");
        String prover = "CVC5";
        int timeout = 10;
        int functionTimeout = 600;
        boolean perOperation = true;
        boolean verify = true;
        int rulesTimeout = 300;
        Side side = null;
        Path workspace = null;
        for (int i = 0; i < args.length; i++) {
            String arg = args[i];
            switch (arg) {
                case "--example" -> examples.add(value(args, ++i, arg));
                case "--all" -> all = true;
                case "--examples-dir" -> examplesDir = Path.of(value(args, ++i, arg));
                case "--out" -> outDir = Path.of(value(args, ++i, arg));
                case "--rules-jar" -> rulesJar = Path.of(value(args, ++i, arg));
                case "--lib-dir" -> libDir = Path.of(value(args, ++i, arg));
                case "--prover" -> prover = value(args, ++i, arg);
                case "--timeout" -> timeout = intValue(args, ++i, arg);
                case "--function-timeout" -> functionTimeout = intValue(args, ++i, arg);
                case "--whole-file" -> perOperation = false;
                case "--no-verify" -> verify = false;
                case "--rules-timeout" -> rulesTimeout = intValue(args, ++i, arg);
                case "--side" -> side = Side.fromId(value(args, ++i, arg));
                case "--workspace" -> workspace = Path.of(value(args, ++i, arg));
                default -> throw new IllegalArgumentException("unknown option: " + arg);
            }
        }
        if (side == null && examples.isEmpty() && !all) {
            throw new IllegalArgumentException("give --example NAME or --all");
        }
        if (outDir == null) {
            outDir = Path.of("comparator-out", LocalDateTime.now().format(DateTimeFormatter.ofPattern("yyyyMMdd_HHmmss")));
        }
        return new ComparatorConfig(
                List.copyOf(examples),
                all,
                examplesDir.toAbsolutePath().normalize(),
                outDir.toAbsolutePath().normalize(),
                rulesJar.toAbsolutePath().normalize(),
                libDir.toAbsolutePath().normalize(),
                prover,
                timeout,
                functionTimeout,
                perOperation,
                verify,
                rulesTimeout,
                side,
                workspace == null ? null : workspace.toAbsolutePath().normalize());
    }

    /** Arguments for the child process that runs {@code side} inside {@code ws}. */
    List<String> childArgs(Side side, Workspace ws) {
        List<String> out = new ArrayList<>();
        out.addAll(List.of("--side", side.id(), "--workspace", ws.root().toString()));
        out.addAll(List.of("--rules-jar", rulesJar.toString(), "--lib-dir", libDir.toString()));
        out.addAll(List.of("--prover", prover, "--timeout", Integer.toString(timeoutSeconds)));
        out.addAll(List.of("--function-timeout", Integer.toString(functionTimeoutSeconds)));
        out.addAll(List.of("--rules-timeout", Integer.toString(rulesTimeoutSeconds)));
        if (!perOperation) {
            out.add("--whole-file");
        }
        if (!verify) {
            out.add("--no-verify");
        }
        return out;
    }

    private static String value(String[] args, int index, String option) {
        if (index >= args.length) {
            throw new IllegalArgumentException(option + " needs a value");
        }
        return args[index];
    }

    private static int intValue(String[] args, int index, String option) {
        try {
            return Integer.parseInt(value(args, index, option));
        } catch (NumberFormatException e) {
            throw new IllegalArgumentException(option + " needs an integer value");
        }
    }
}
